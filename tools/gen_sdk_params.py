#!/usr/bin/env python3
"""vst/params.json -> src/sdk/params_gen.h: the parameter table of the SDK front end (src/sdk/Model72Plugin.cpp).
Order = vst/params.json = vst/params.lock (checked): the VST parameter index of the released 1.0.1 build, which saved
projects (automation) and the skin bind to. FROZEN: new parameters are only appended (APPENDED below, after the 72)."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst/params.json")))["params"]
lock = [l.strip() for l in open(os.path.join(ROOT, "vst/params.lock")) if l.strip()]
if [p["key"] for p in P] != lock:
    raise SystemExit("vst/params.json no longer matches vst/params.lock: the 1.0.1 order is frozen")
# flags: 1 momentary, 2 text (formatValue shows engine/plugin text), 4 float display, 8 choice,
#        16 UI only (never reaches the engine), 32 pushed (the engine changes it: read back + notify), 64 read-only
# APPENDED: parameters after the frozen 72 (the SDK version's own), as (key, name, min, max, default, flags).
APPENDED = []   # filled in by the front end phase (presets / naming keyboard / ui_open)
out = ["/* generated by tools/gen_sdk_params.py: do not edit. One row per parameter, in the frozen VST order. */", "#pragma once",
       "enum { kMomentary = 1, kText = 2, kFloat = 4, kChoice = 8, kUi = 16, kPushed = 32, kReadOnly = 64 };",
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; };", ""]
rows = []
for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n = 0, "nullptr", 0
    if "options" in p:
        fl |= 8
        opts = p["options"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        lo, hi, d = 0, len(opts) - 1, opts.index(p["default"])
    else:
        lo, hi, d = p["min"], p["max"], p["default"]
        if p.get("display") != "int": fl |= 4
    if k == "auto_db": fl |= 2 | 32 | 64          # AUTO GAIN's correction readout (engine text)
    if k.startswith("dot_"): fl |= 32 | 64        # the STEREO field's live voice dots
    rows.append('    {%s, %s, %sf, %sf, %sf, %d, %s, %d},' % (json.dumps(k), json.dumps(p["name"]), float(lo), float(hi), float(d), fl, ch, n))
for k, name, lo, hi, d, fl in APPENDED:
    rows.append('    {%s, %s, %sf, %sf, %sf, %d, nullptr, 0},' % (json.dumps(k), json.dumps(name), float(lo), float(hi), float(d), fl))
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumFrozen = %d;   // the 1.0.1 parameters (engine keys)" % len(P),
        "static const int kNumParams = %d;" % (len(P) + len(APPENDED)), ""]
open(os.path.join(ROOT, "src/sdk/params_gen.h"), "w").write("\n".join(out))
print("src/sdk/params_gen.h: %d params (%d frozen)" % (len(P) + len(APPENDED), len(P)))
