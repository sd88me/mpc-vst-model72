#!/usr/bin/env python3
"""vst/params.json (+ the SDK version's appended params) -> src/params_gen.h; vst/presets.json -> src/presets_gen.h.

Order = vst/params.lock: 0..71 are the released 1.0.1 build's parameters (vst/params.json, FROZEN), then the SDK version's own,
appended (APPENDED below). Saved projects (automation) and the skin bind to these indices. Append only: the script refuses
any other order, and writes the lock's new tail itself the first time a new appended key shows up."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst/params.json")))["params"]
LOCKF = os.path.join(ROOT, "vst/params.lock")
lock = [l.strip() for l in open(LOCKF) if l.strip()]

KB_CHARS = "1234567890QWERTYUIOPASDFGHJKLZXCVBNM-"
KB_KEYS = [("kb_" + ("dash" if c == "-" else c.lower()), "Key " + c) for c in KB_CHARS] + \
          [("kb_space", "Key Space"), ("kb_bksp", "Key Delete"), ("kb_shift", "Key Shift"), ("kb_cancel", "Key Cancel"), ("kb_save", "Key Save")]
APPENDED = [("fav_add", "+ Preset"), ("fav_del", "- Preset"), ("fav_name", "Preset Name"), ("kb_open", "Keyboard")] + KB_KEYS + \
           [("pitch_wheel", "Pitch Wheel")]   # 2.0: the OUTPUT tab's pitch wheel (1.0.1 drew it, had no control), -1..1 -> MIDI pitch bend
FAV_SLOTS = 64
FAV_NAME_MAX = 20

keys = [p["key"] for p in P] + [k for k, _ in APPENDED]
if len(P) != 72 or keys[:len(lock)] != lock:
    raise SystemExit("vst/params.lock: the order is frozen (append only); params.json + APPENDED no longer start with it")
if len(keys) > len(lock):
    with open(LOCKF, "a") as f:
        f.write("".join(k + "\n" for k in keys[len(lock):]))
    print("vst/params.lock: appended %d" % (len(keys) - len(lock)))

# flags: 1 momentary, 2 text (formatValue shows text; the value is a counter), 4 float, 8 choice, 16 local (the front end's own,
# never an engine key), 32 pushed (the engine changes it: read back and told to the host), 64 read-only, 128 not automatable
FL = dict(kMomentary=1, kText=2, kFloat=4, kChoice=8, kLocal=16, kPushed=32, kReadOnly=64, kNoAuto=128)
F = lambda x: repr(float(x)) + "f"
out = ["/* generated by tools/gen_sdk_params.py: do not edit. One row per parameter, in the frozen VST order (vst/params.lock). */",
       "#pragma once",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; };", ""]
rows = []
for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n = 0, "nullptr", 0
    if "options" in p:
        fl |= FL["kChoice"]
        opts = p["options"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        lo, hi, d = 0, len(opts) - 1, opts.index(p["default"])
    else:
        lo, hi, d = p["min"], p["max"], p["default"]
        if p.get("display") != "int": fl |= FL["kFloat"]
    if k == "auto_db":            # AUTO GAIN's correction: engine text ("-3.2"), read only
        fl = FL["kText"] | FL["kPushed"] | FL["kReadOnly"] | FL["kNoAuto"]
        lo, hi, d = 0, 1023, 0
    if k.startswith("dot_"):      # the STEREO field's live voice dots, read only
        fl |= FL["kPushed"] | FL["kReadOnly"] | FL["kNoAuto"]
    rows.append("    {%s, %s, %s, %s, %s, %d, %s, %d}," % (json.dumps(k), json.dumps(p["name"]), F(lo), F(hi), F(d), fl, ch, n))
for k, name in APPENDED:
    fl, lo, hi = FL["kLocal"] | FL["kMomentary"] | FL["kNoAuto"], 0, 1
    if k == "fav_name": fl, hi = FL["kLocal"] | FL["kText"] | FL["kNoAuto"], 1023
    elif k == "kb_open": fl = FL["kLocal"] | FL["kNoAuto"]
    elif k == "pitch_wheel": fl, lo = FL["kLocal"] | FL["kFloat"], -1
    rows.append("    {%s, %s, %s, %s, 0.0f, %d, nullptr, 0}," % (json.dumps(k), json.dumps(name), F(lo), F(hi), fl))
idx = {k: i for i, k in enumerate(keys)}
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumParams = %d;" % len(keys),
        "static const int kNumEngineParams = %d;   // 0 .. this - 1: the engine's keys (the 1.0.1 table)" % len(P),
        "static const int kAutoDb = %d, kDot1 = %d, kDots = 10;" % (idx["auto_db"], idx["dot_1"]),
        "static const int kFavAdd = %d, kFavDel = %d, kFavName = %d, kKbOpen = %d, kKbFirst = %d, kKbCount = %d;" % (
            idx["fav_add"], idx["fav_del"], idx["fav_name"], idx["kb_open"], idx[KB_KEYS[0][0]], len(KB_KEYS)),
        "static const int kFavSlots = %d, kFavNameMax = %d;" % (FAV_SLOTS, FAV_NAME_MAX),
        "static const int kPitchWheel = %d;" % idx["pitch_wheel"],
        "static const char kKbChars[] = %s;   // the character keys from kKbFirst (then space, delete, shift, cancel, save)" % json.dumps(KB_CHARS), ""]
open(os.path.join(ROOT, "src/params_gen.h"), "w").write("\n".join(out))

# Factory presets (the 1.0.1 PRESET menu): name + the engine's own state text (options as indices), so a pick is one "state" set.
PR = json.load(open(os.path.join(ROOT, "vst/presets.json")))["presets"]
byk = {p["key"]: p for p in P}
po = ["/* generated by tools/gen_sdk_params.py from vst/presets.json: do not edit. */", "#pragma once",
      "struct FactoryPreset { const char *name, *state; };", "static const FactoryPreset g_factory[] = {"]
for pr in PR:
    kv = []
    for k, v in pr["values"].items():
        if k == "quality": continue   # QUALITY is not part of a preset (LO / HI is the device's choice)
        if "options" in byk[k]: v = byk[k]["options"].index(v)
        kv.append("%s=%s" % (k, v))
    po.append("    {%s, %s}," % (json.dumps(pr["name"]), json.dumps(";".join(kv))))
po += ["};", "static const int kFactory = %d;" % len(PR), ""]
open(os.path.join(ROOT, "src/presets_gen.h"), "w").write("\n".join(po))
print("src/params_gen.h: %d params (%d frozen); src/presets_gen.h: %d presets, %d favourite slots" % (len(keys), len(P), len(PR), FAV_SLOTS))
