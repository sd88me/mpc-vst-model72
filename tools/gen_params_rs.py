#!/usr/bin/env python3
"""vst/params.json -> engine/ca72-mpc/src/params.rs (the engine's table of the same parameters, in VST order)."""
import json, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ps = json.load(open(os.path.join(root, "vst", "params.json")))["params"]
out = ["// generated by tools/gen_params_rs.py from vst/params.json: do not edit", ""]
out.append("pub const COUNT: usize = %d;" % len(ps))
for i, p in enumerate(ps):
    out.append("pub const %s: usize = %d;" % (p["key"].upper(), i))
out.append("")
out.append("pub const KEYS: [&str; COUNT] = [%s];" % ", ".join('"%s"' % p["key"] for p in ps))
def dflt(p):
    if "options" in p:
        return float(p["options"].index(p["default"]))
    return float(p["default"])
out.append("pub const DEFAULTS: [f64; COUNT] = [%s];" % ", ".join(repr(dflt(p)) for p in ps))
out.append("/// Option count (0 for a continuous parameter).")
out.append("pub const OPTIONS: [usize; COUNT] = [%s];" % ", ".join(str(len(p.get("options", []))) for p in ps))
out.append("pub const MIN: [f64; COUNT] = [%s];" % ", ".join(repr(float(p.get("min", 0))) for p in ps))
out.append("pub const MAX: [f64; COUNT] = [%s];" % ", ".join(repr(float(p.get("max", len(p.get("options", [1])) - 1))) for p in ps))
open(os.path.join(root, "engine", "ca72-mpc", "src", "params.rs"), "w").write("\n".join(out) + "\n")
